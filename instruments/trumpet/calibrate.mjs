// Measures the playing pitch of the model across range and dynamics and writes tuning.mjs.
// The lip/bore system settles a little sharp of the bore resonance, more so when blown hard.
// Run: node instruments/trumpet/calibrate.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SR, midiToHz } from '../../lib/audio.mjs';
import { render, tune, meta } from '../trumpet.mjs';
import { TABLE } from './tuning.mjs';

const VS = [0.1, 0.25, 0.4, 0.55, 0.7, 0.85, 1.0];

function fft(re, im) {
  const n = re.length;
  for (let i = 1, j = 0; i < n; i++) {
    let bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) { [re[i], re[j]] = [re[j], re[i]]; [im[i], im[j]] = [im[j], im[i]]; }
  }
  for (let len = 2; len <= n; len <<= 1) {
    const ang = -2 * Math.PI / len;
    for (let i = 0; i < n; i += len) {
      for (let j = 0; j < len / 2; j++) {
        const cr = Math.cos(ang * j), ci = Math.sin(ang * j), a = i + j, b = a + len / 2;
        const tr = re[b] * cr - im[b] * ci, ti = re[b] * ci + im[b] * cr;
        re[b] = re[a] - tr; im[b] = im[a] - ti; re[a] += tr; im[a] += ti;
      }
    }
  }
}

// Fundamental from a Hann-windowed spectrum with log-parabolic peak interpolation.
export function measureCents(x, midi, t0 = 0.45, N = 32768) {
  const f = midiToHz(midi), re = new Float64Array(N), im = new Float64Array(N), a = Math.round(t0 * SR);
  for (let i = 0; i < N; i++) re[i] = (x[a + i] || 0) * (0.5 - 0.5 * Math.cos(2 * Math.PI * i / N));
  fft(re, im);
  const bin = SR / N;
  let kb = 0, pb = 0;
  for (let k = Math.round(f * 0.9 / bin); k < f * 1.1 / bin; k++) { const p = re[k] ** 2 + im[k] ** 2; if (p > pb) { pb = p; kb = k; } }
  const P = (k) => Math.log(re[k] ** 2 + im[k] ** 2);
  const d = 0.5 * (P(kb - 1) - P(kb + 1)) / (P(kb - 1) - 2 * P(kb) + P(kb + 1));
  return 1200 * Math.log2((kb + d) * bin / f);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [lo, hi] = meta.range;
  const cents = [];
  for (let m = lo; m <= hi; m++) {
    const row = VS.map((v) => {
      const x = render({ midi: m, velocity: v, duration: 1.2, vibrato: 0, seed: 3 });
      const prev = TABLE ? tuneLookup(m, v) : 0;
      return +(prev + measureCents(x, m)).toFixed(2);
    });
    cents.push(row);
    console.log(m, row.join(' '));
  }
  const src = `// Generated by calibrate.mjs: pitch offset (cents) of the model without correction, per note and dynamic.
export const TABLE = ${JSON.stringify({ lo, hi, vs: VS, cents })};
export function tuningCents(midi, v) {
  const m = Math.max(TABLE.lo, Math.min(TABLE.hi, Math.round(midi))) - TABLE.lo;
  const vs = TABLE.vs, row = TABLE.cents[m];
  if (v <= vs[0]) return row[0];
  for (let i = 1; i < vs.length; i++) if (v <= vs[i]) return row[i - 1] + (v - vs[i - 1]) / (vs[i] - vs[i - 1]) * (row[i] - row[i - 1]);
  return row[vs.length - 1];
}
`;
  writeFileSync(new URL('./tuning.mjs', import.meta.url), src);
}

function tuneLookup(m, v) { return tune.correct ? tuningCentsPrev(m, v) : 0; }
function tuningCentsPrev(m, v) {
  const vs = TABLE.vs, row = TABLE.cents[m - TABLE.lo];
  if (v <= vs[0]) return row[0];
  for (let i = 1; i < vs.length; i++) if (v <= vs[i]) return row[i - 1] + (v - vs[i - 1]) / (vs[i] - vs[i - 1]) * (row[i] - row[i - 1]);
  return row[vs.length - 1];
}
