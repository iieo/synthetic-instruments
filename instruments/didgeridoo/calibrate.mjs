// Measures the drone pitch of the uncorrected model over range, blowing pressure and vowel, and
// writes tuning.mjs. Run: node instruments/didgeridoo/calibrate.mjs
import { writeFileSync } from 'node:fs';
import { render, meta } from '../didgeridoo.mjs';
import { measureCents } from '../trumpet/calibrate.mjs';
import { tuningCents } from './tuning.mjs';

const LOOKUP = `const at = (xs, x) => {
  const j = Math.max(0, Math.min(xs.length - 2, xs.findIndex((q) => q >= x) - 1));
  return [j, Math.max(0, Math.min(1, (x - xs[j]) / (xs[j + 1] - xs[j])))];
};
export function tuningCents(midi, v, w) {
  if (!TABLE) return 0;
  const m = Math.max(TABLE.lo, Math.min(TABLE.hi, midi)) - TABLE.lo, m0 = Math.min(Math.floor(m), TABLE.hi - TABLE.lo - 1), fm = m - m0;
  const [i, fi] = at(TABLE.vs, Math.max(0, Math.min(1, v))), [k, fk] = at(TABLE.ws, Math.max(0, Math.min(1, w)));
  let c = 0;
  for (const [dm, gm] of [[0, 1 - fm], [1, fm]]) for (const [di, gi] of [[0, 1 - fi], [1, fi]]) for (const [dk, gk] of [[0, 1 - fk], [1, fk]]) {
    c += gm * gi * gk * TABLE.cents[m0 + dm][i + di][k + dk];
  }
  return c;
}
`;

const VS = [0, 0.25, 0.5, 0.75, 1], WS = [0, 0.25, 0.5, 0.75, 1];
const [lo, hi] = meta.range;
const cents = [];
for (let m = lo; m <= hi; m++) {
  const row = VS.map((v) => WS.map((w) => {
    const prev = tuningCents(m, v, w), g = prev ? 0 : 190;
    const x = render({ midi: m, velocity: v, vowel: w, duration: 1.3, seed: 3 });
    return +(prev + g + measureCents(x, m + g / 100, 0.55)).toFixed(2);
  }));
  cents.push(row);
  console.log(m, row.map((r) => r.join('/')).join(' '));
}
writeFileSync(new URL('./tuning.mjs', import.meta.url), `// Generated by calibrate.mjs: drone pitch offset (cents) of the uncorrected model per note, pressure and vowel.
export const TABLE = ${JSON.stringify({ lo, hi, vs: VS, ws: WS, cents })};
${LOOKUP}`);
