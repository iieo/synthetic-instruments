// Measures the playing pitch of the model for every partial, slide setting and dynamic and writes
// tuning.mjs. The lips pull the coupled system sharp of the bore resonance, more so when blown hard.
// Run twice after any model change: node instruments/trombone/calibrate.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SR } from '../../lib/audio.mjs';
import { play } from './voice.mjs';
import { PARTIALS, PEDAL, S_MIN, S_MAX, sMax } from './slide.mjs';
import { tuningCents } from './tuning.mjs';

const SS = [S_MIN, 0, 1, 2, 3, 4, 5, 6, S_MAX];
const VS = [0.05, 0.25, 0.4, 0.55, 0.7, 0.85, 1.0];

function fft(re, im) {
  const n = re.length;
  for (let i = 1, j = 0; i < n; i++) {
    let bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) { [re[i], re[j]] = [re[j], re[i]]; [im[i], im[j]] = [im[j], im[i]]; }
  }
  for (let len = 2; len <= n; len <<= 1) {
    const ang = -2 * Math.PI / len;
    for (let i = 0; i < n; i += len) {
      for (let j = 0; j < len / 2; j++) {
        const cr = Math.cos(ang * j), ci = Math.sin(ang * j), a = i + j, b = a + len / 2;
        const tr = re[b] * cr - im[b] * ci, ti = re[b] * ci + im[b] * cr;
        re[b] = re[a] - tr; im[b] = im[a] - ti; re[a] += tr; im[a] += ti;
      }
    }
  }
}

// Fundamental near f from a Hann-windowed spectrum with log-parabolic peak interpolation.
export function measureCents(x, f, t0 = 0.45, N = 32768) {
  const re = new Float64Array(N), im = new Float64Array(N), a = Math.round(t0 * SR);
  for (let i = 0; i < N; i++) re[i] = (x[a + i] || 0) * (0.5 - 0.5 * Math.cos(2 * Math.PI * i / N));
  fft(re, im);
  const bin = SR / N;
  let kb = 0, pb = 0;
  for (let k = Math.round(f * 0.94 / bin); k < f * 1.06 / bin; k++) { const p = re[k] ** 2 + im[k] ** 2; if (p > pb) { pb = p; kb = k; } }
  const P = (k) => Math.log(re[k] ** 2 + im[k] ** 2);
  const d = 0.5 * (P(kb - 1) - P(kb + 1)) / (P(kb - 1) - 2 * P(kb) + P(kb + 1));
  return 1200 * Math.log2((kb + d) * bin / f);
}

export const pitchHz = (n, s) => n * 440 * 2 ** ((PEDAL - 69 - s) / 12);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const cents = PARTIALS.map((n) => SS.map((sGrid) => {
    const s = Math.min(sGrid, sMax(n));
    const row = VS.map((v) => {
      const x = play({ plan: { s: () => s, n: () => n }, v0: v, v1: v, duration: 1.3, seed: 3, vibrato: 0, tongue: 1 });
      return +(tuningCents(n, s, v) + measureCents(x, pitchHz(n, s))).toFixed(2);
    });
    console.log(n, s, row.join(' '));
    return row;
  }));
  const src = `// Generated by calibrate.mjs: pitch offset (cents) of the uncorrected model per partial, slide
// setting (semitones) and dynamic.
export const TABLE = ${JSON.stringify({ partials: PARTIALS, ss: SS, vs: VS, cents })};
const seg = (xs, x) => {
  if (x <= xs[0]) return [0, 0];
  for (let i = 1; i < xs.length; i++) if (x <= xs[i]) return [i - 1, (x - xs[i - 1]) / (xs[i] - xs[i - 1])];
  return [xs.length - 2, 1];
};
export function tuningCents(n, s, v) {
  let p = 0;
  for (let i = 1; i < TABLE.partials.length; i++) if (Math.abs(TABLE.partials[i] - n) < Math.abs(TABLE.partials[p] - n)) p = i;
  const [i, a] = seg(TABLE.ss, s), [j, b] = seg(TABLE.vs, v), c = TABLE.cents[p];
  const r0 = c[i][j] + b * (c[i][j + 1] - c[i][j]), r1 = c[i + 1][j] + b * (c[i + 1][j + 1] - c[i + 1][j]);
  return r0 + a * (r1 - r0);
}
`;
  writeFileSync(new URL('./tuning.mjs', import.meta.url), src);
}
