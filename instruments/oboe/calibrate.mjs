// Measures the playing pitch of the model across range and dynamics and writes tuning.mjs.
// The reed, whose resonance sits just above the note, and the filters in the bore pull the regime
// away from the ideal cone resonance; the table stores that offset so render() can undo it.
// Run: node instruments/oboe/calibrate.mjs   (twice: the second pass measures what is left)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SR, midiToHz } from '../../lib/audio.mjs';
import { render, meta } from '../oboe.mjs';
import { tuningCents } from './tuning.mjs';

const VS = [0.05, 0.3, 0.55, 0.8, 1];

function fft(re, im) {
  const n = re.length;
  for (let i = 1, j = 0; i < n; i++) {
    let bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) { [re[i], re[j]] = [re[j], re[i]]; [im[i], im[j]] = [im[j], im[i]]; }
  }
  for (let len = 2; len <= n; len <<= 1) {
    const ang = -2 * Math.PI / len;
    for (let i = 0; i < n; i += len) {
      for (let j = 0; j < len / 2; j++) {
        const cr = Math.cos(ang * j), ci = Math.sin(ang * j), a = i + j, b = a + len / 2;
        const tr = re[b] * cr - im[b] * ci, ti = re[b] * ci + im[b] * cr;
        re[b] = re[a] - tr; im[b] = im[a] - ti; re[a] += tr; im[a] += ti;
      }
    }
  }
}

// Fundamental near the nominal frequency: Hann window, log-parabolic peak interpolation.
export function measureCents(x, midi, t0 = 0.5, N = 32768) {
  const f = midiToHz(midi), re = new Float64Array(N), im = new Float64Array(N), a = Math.round(t0 * SR);
  for (let i = 0; i < N; i++) re[i] = (x[a + i] || 0) * (0.5 - 0.5 * Math.cos(2 * Math.PI * i / N));
  fft(re, im);
  const bin = SR / N, P = (k) => Math.log(re[k] ** 2 + im[k] ** 2 + 1e-30);
  let kb = 0;
  for (let k = Math.round(f * 0.92 / bin); k < f * 1.08 / bin; k++) if (!kb || P(k) > P(kb)) kb = k;
  const d = 0.5 * (P(kb - 1) - P(kb + 1)) / (P(kb - 1) - 2 * P(kb) + P(kb + 1));
  return 1200 * Math.log2((kb + d) * bin / f);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [lo, hi] = meta.range;
  const table = {};
  for (const preset of meta.presets) {
    const rows = [];
    for (let m = lo; m <= hi; m++) {
      const row = VS.map((v) => {
        const x = render({ midi: m, velocity: v, duration: 1.3, vibrato: 0, breath: 0, seed: 3, preset });
        return +(tuningCents(preset, m, v) + measureCents(x, m)).toFixed(2);
      });
      rows.push(row);
      console.log(preset, m, row.join(' '));
    }
    table[preset] = rows;
  }
  const src = `// Generated by calibrate.mjs: pitch offset (cents) of the uncorrected model per preset, note and dynamic.
export const TABLE = ${JSON.stringify({ lo, hi, vs: VS, cents: table })};

function row(r, v) {
  const vs = TABLE.vs;
  if (v <= vs[0]) return r[0];
  for (let i = 1; i < vs.length; i++) if (v <= vs[i]) return r[i - 1] + (v - vs[i - 1]) / (vs[i] - vs[i - 1]) * (r[i] - r[i - 1]);
  return r[vs.length - 1];
}

export function tuningCents(preset, midi, v) {
  const rows = TABLE.cents[preset];
  if (!rows) return 0;
  const m = Math.max(TABLE.lo, Math.min(TABLE.hi, midi)) - TABLE.lo, i = Math.floor(m), fr = m - i;
  const a = row(rows[i], v);
  return fr > 0 && i + 1 < rows.length ? a + fr * (row(rows[i + 1], v) - a) : a;
}
`;
  writeFileSync(new URL('./tuning.mjs', import.meta.url), src);
}
